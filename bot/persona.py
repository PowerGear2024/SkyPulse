SHORT_NAME = "Даня"
CITY = "Одесса"
CITY_GENITIVE = "Одессы"
BIRTH_YEAR = 1998


def current_age(today: date | None = None) -> int:
    """Возраст Дани на указанную дату (по умолчанию — сегодня)."""
    today = today or date.today()
    age = today.year - BIRTH_YEAR
    # День рождения условно 1 января — для роли достаточно года
    return max(age, 1)


def age_phrase(today: date | None = None) -> str:
    """Фраза вида «28-летний» для приветствия."""
    return f"{current_age(today)}-летний"


